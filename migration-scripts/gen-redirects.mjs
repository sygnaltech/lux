/**
 * Generate `public/_redirects` from migration-scripts/redirects.config.mjs.
 *
 *   node migration-scripts/gen-redirects.mjs
 *
 * Runs as `prebuild`, so the file is always in step with the config and there
 * is no hand-maintained copy to forget. `public/` is copied verbatim into
 * ./dist by Astro, and Cloudflare's asset layer reads `_redirects` from there.
 *
 * WHY THIS IS THE EDGE FILE AND NOT JUST MIDDLEWARE
 *
 * A redirect in `_redirects` is answered by Cloudflare before the Worker is
 * invoked at all: no isolate start, no Sanity query, no cost. The middleware
 * copy exists only to catch a request that reaches the Worker anyway — the
 * documented caveat is that `_redirects` is "not applied to requests served by
 * your Worker code", and rather than depend on exactly where that boundary
 * falls, both paths are covered. Cheap insurance on URLs that are already
 * indexed.
 *
 * The generated file is committed. It is build output, but it is also the
 * artifact that proves what the live site will do with an old URL, and that is
 * worth being able to read in a diff.
 *
 * LAYOUT: `WEB` assumes the Astro app sits in `web/`. In a single-package repo,
 * point it at ROOT instead — it is the one path assumption in this file.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { REDIRECTS, STATUS } from './redirects.config.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const WEB = join(ROOT, 'web');
const OUT = join(WEB, 'public/_redirects');

// Cloudflare's limits, worth failing on rather than discovering at deploy.
const MAX_RULES = 2000;
const MAX_LINE = 1000;

const problems = [];
const seen = new Set();

for (const { from, to } of REDIRECTS) {
  if (!from?.startsWith('/')) problems.push(`from must be an absolute path: ${from}`);
  if (!to) problems.push(`missing destination for ${from}`);
  if (from !== '/' && from?.endsWith('/')) problems.push(`from must not end in a slash: ${from}`);
  if (from?.includes('?')) problems.push(`from must not carry a query string: ${from}`);
  if (from === to) problems.push(`redirects to itself: ${from}`);
  if (seen.has(from)) problems.push(`duplicate source: ${from}`);
  seen.add(from);
  if (`${from} ${to} ${STATUS}`.length > MAX_LINE) problems.push(`line too long: ${from}`);
}

if (REDIRECTS.length > MAX_RULES) {
  problems.push(`${REDIRECTS.length} rules exceeds Cloudflare's ${MAX_RULES} static redirects`);
}

if (problems.length) {
  console.error('\n_redirects NOT written — fix migration-scripts/redirects.config.mjs:\n');
  for (const p of problems) console.error(`  ${p}`);
  console.error('');
  process.exit(1);
}

const body = [
  '# GENERATED by migration-scripts/gen-redirects.mjs — do not edit.',
  '# Source of truth: migration-scripts/redirects.config.mjs',
  '',
  ...REDIRECTS.map(({ from, to, why }) => `${why ? `# ${why}\n` : ''}${from} ${to} ${STATUS}`),
  '',
].join('\n');

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body, 'utf8');

console.log(
  `ok    public/_redirects — ${REDIRECTS.length} redirect${REDIRECTS.length === 1 ? '' : 's'}`,
);
